"""Render backtest outputs as a self-contained markdown report."""

from __future__ import annotations

import math

import pandas as pd


def _fmt(v, digits: int = 2) -> str:
    if isinstance(v, bool):
        return "yes" if v else ""
    if isinstance(v, float):
        if math.isnan(v):
            return "–"
        return f"{v:.{digits}f}"
    return str(v)


def md_table(df: pd.DataFrame, digits: dict[str, int] | None = None, index: bool = False) -> str:
    digits = digits or {}
    if index:
        df = df.reset_index()
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    # itertuples keeps per-column types (iterrows would upcast int years to float)
    for row in df.itertuples(index=False):
        cells = (_fmt(v.item() if hasattr(v, "item") else v, digits.get(c, 2)) for c, v in zip(cols, row))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _p_label(p: float) -> str:
    if isinstance(p, float) and math.isnan(p):
        return "–"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def headline_table(summary: pd.DataFrame, horizon: int) -> str:
    s = summary[summary["horizon"] == horizon].copy()
    s = s.sort_values(["oracle", "MAE"])
    s["DM p vs Naive"] = s["DM_p"].map(_p_label)
    s["Model"] = s["model"] + s["oracle"].map(lambda o: " ⚠ oracle" if o else "")
    s["Coverage 95%"] = s["coverage_95"].map(lambda c: "–" if math.isnan(c) else f"{c:.0%}")
    s["Dir. acc."] = s["dir_acc"].map(lambda c: "–" if math.isnan(c) else f"{c:.0%}")
    out = s[["Model", "MAE", "RMSE", "MAPE", "MASE", "rel_MAE", "DM p vs Naive", "Dir. acc.", "Coverage 95%"]]
    out = out.rename(columns={"MAE": "MAE ($)", "RMSE": "RMSE ($)", "MAPE": "MAPE (%)", "rel_MAE": "MAE / Naive"})
    return md_table(out, {"MAE / Naive": 3})


def render(
    *,
    meta: dict,
    summary: pd.DataFrame,
    by_year: pd.DataFrame,
    legacy: pd.DataFrame,
    fit_log: pd.DataFrame,
    horizons: list[int],
) -> str:
    parts = [
        "# Walk-forward backtest — Brent weekly forecasts",
        "",
        "_Generated by `python -m evaluation.run_backtest`. Do not edit by hand; rerun instead._",
        "",
        "## Setup",
        "",
        f"- Data: {meta['n_obs']} weekly observations, {meta['data_start']} → {meta['data_end']}",
        f"- Data fingerprint: `{meta['data_fingerprint']}`",
        f"- Code version: `{meta['git_commit']}`",
        f"- Test origins: {meta['n_origins']} (every {meta['step']} week(s)), "
        f"{meta['first_origin']} → {meta['last_origin']}",
        f"- Horizon: 1–{meta['horizon']} weeks; "
        + (
            f"parameters re-estimated every {meta['refit_every']} weeks on all data available at that point"
            if meta["refit_every"]
            else "parameters estimated once on the training set, then frozen"
        ),
        "- Between re-estimations the model state is updated with each new week (Kalman filter), "
        "so every forecast starts from the latest observed price",
        f"- MASE scale (in-sample naive one-step MAE on the training set): ${meta['mase_scale']:.2f}",
        "",
        "Models marked **⚠ oracle** are given the *realised* future macro variables. "
        "That information does not exist when a real forecast is made, so they show an "
        "upper bound, not deployable accuracy.",
        "",
        "## 1. The original evaluation, reproduced",
        "",
        "The notebook scored one forecast made at the end of training, covering every remaining "
        f"week ({meta['legacy_horizon']} weeks), with the realised macro variables supplied. "
        "Re-running that setup here:",
        "",
        md_table(legacy, {"MAE ($)": 2, "MAPE (%)": 2, "RMSE ($)": 2}),
        "",
        "## 2. Walk-forward results",
        "",
        "`MAE / Naive` below 1 means the model beats a random walk. The DM p-value tests whether "
        "that difference is larger than chance (Diebold–Mariano with Harvey–Leybourne–Newbold "
        "correction, absolute-error loss). Coverage is the share of outcomes inside the 95% "
        "interval; a well-calibrated interval scores close to 95%.",
        "",
    ]
    for h in horizons:
        parts += [f"### {h}-week ahead", "", headline_table(summary, h), ""]
    parts += [
        f"## 3. {meta['by_year_horizon']}-week-ahead MAE ($) by target year",
        "",
        "Accuracy depends heavily on the market regime, so a single average hides a lot.",
        "",
        md_table(by_year, index=True),
        "",
        "## 4. Parameter estimation log",
        "",
        md_table(fit_log, {"seconds": 1, "aic": 1}),
        "",
    ]
    return "\n".join(parts)
