"""Step 1c: are the prediction intervals trustworthy, and can conformal fix them?

Usage:
    python -m evaluation.run_calibration          # ~5 minutes

Forecast origins start in 2016 so that, by the 2022 evaluation start, every
conformal method has years of resolved out-of-sample errors to calibrate on.
Only origins from the step-1a evaluation start (2022-01-02) are scored.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import pandas as pd

from evaluation import calibration, conformal, report
from evaluation.backtest import BacktestConfig, run_backtest
from evaluation.data import data_fingerprint, load_dataset, train_size
from evaluation.forecasters import Naive, SarimaxEstimator, SarimaxForecaster
from evaluation.run_backtest import ROOT, _git_commit, _progress

HEADLINE_HORIZONS = [1, 4, 12]


def _pct(x: float) -> str:
    return f"{x:.1%}"


def _level_table(summary: pd.DataFrame, horizon: int, level: float) -> str:
    s = summary[(summary["horizon"] == horizon) & (summary["level"] == level)].copy()
    s = s.sort_values("interval_score")
    out = pd.DataFrame(
        {
            "Model": s["model"],
            "Interval method": s["method"],
            "Coverage": s["coverage"].map(_pct),
            "95% CI of coverage": [f"{_pct(a)} – {_pct(b)}" for a, b in zip(s["cov_ci_lo"], s["cov_ci_hi"])],
            "Calibrated?": s["calibrated"].map(lambda c: "yes" if c else "no"),
            "Mean width ($)": s["mean_width"],
            "Interval score": s["interval_score"],
        }
    )
    return report.md_table(out)


def _regime_table(by_regime: pd.DataFrame, level: float) -> str:
    s = by_regime[(by_regime["level"] == level) & by_regime["horizon"].isin(HEADLINE_HORIZONS)]
    pivot = s.pivot_table(
        index=["model", "method", "horizon"], columns="regime", values="coverage", sort=False
    ).reset_index()
    for col in pivot.columns[3:]:
        pivot[col] = pivot[col].map(_pct)
    return report.md_table(pivot)


def render(meta, summary, by_regime, selection, scorecard, verdict) -> str:
    sel = selection.copy()
    sel["coverage"] = sel["coverage"].map(_pct)
    sel["level"] = sel["level"].map(lambda v: f"{v:.0%}")
    parts = [
        "# Step 1c — Calibration of prediction intervals",
        "",
        "_Generated by `python -m evaluation.run_calibration`. Do not edit by hand; rerun instead._",
        "",
        "## Setup",
        "",
        f"- Forecast origins: {meta['first_origin']} → {meta['last_origin']} (weekly); "
        f"**scored only from {meta['eval_start']}** ({meta['n_eval_origins']} origins)",
        f"- Earlier origins exist only to give conformal methods out-of-sample errors to learn from",
        f"- Conformal window: last {meta['window']} resolved forecasts per horizon "
        f"(min {meta['min_calib']}); ACI step size γ = {meta['gamma']}; errors measured as |log(actual / forecast)|",
        f"- Point forecasters: Naive and SARIMA (no exog), the best two from steps 1a–1b",
        f"- Vol-scaled variants divide each error by the trailing {meta['vol_window']}-week volatility of "
        "weekly log returns at its forecast origin, and multiply today's interval by today's volatility",
        f"- SARIMA parameters re-estimated every 52 weeks from {meta['first_origin']}, so its point "
        "forecasts differ slightly from the step-1a run",
        f"- Data fingerprint: `{meta['data_fingerprint']}` · code `{meta['git_commit']}`",
        "",
        "## Decision rule (fixed before running)",
        "",
        "An interval method is **calibrated** at a horizon and level if the nominal level lies inside "
        "the 95% confidence interval of its observed coverage. That interval uses Newey–West standard "
        "errors, because hits from overlapping multi-week forecasts are correlated. Among calibrated "
        "methods, the one with the lowest mean **interval score** (Gneiting & Raftery, 2007) is chosen. "
        "The interval score charges the width plus 2/α times any miss distance, so a method cannot win by "
        "being uselessly wide or overconfidently narrow.",
        "",
        "## Selected method per horizon and level",
        "",
        report.md_table(sel, {"mean_width": 2, "interval_score": 2}),
        "",
        "## Regime scorecard (volatility-scaling experiment)",
        "",
        "Fixed before running: a cell is one horizon (1, 4, 12 weeks) × level (80%, 95%). Volatility "
        "scaling succeeds if some vol-scaled method is calibrated in **both** regimes (2022 crisis and "
        "2023+ calmer) in more cells than every unscaled method.",
        "",
        report.md_table(scorecard),
        "",
        verdict,
        "",
        "_The scorecard measures coverage only, not width. Read it together with the interval-score "
        "tables below: a method can be calibrated in both regimes and still be too wide to be useful._",
        "",
    ]
    for level in (0.95, 0.8):
        parts += [f"## {level:.0%} intervals", ""]
        for h in HEADLINE_HORIZONS:
            parts += [f"### {h}-week ahead", "", _level_table(summary, h, level), ""]
    parts += [
        "## Coverage by regime (95% intervals)",
        "",
        "Average coverage can hide failures in exactly the periods that matter. "
        "2022 had the war-driven spike and collapse; 2023 onwards was calmer.",
        "",
        _regime_table(by_regime, 0.95),
        "",
        "## 50% intervals (coverage only)",
        "",
        report.md_table(
            summary[(summary["level"] == 0.5) & summary["horizon"].isin(HEADLINE_HORIZONS)][
                ["model", "method", "horizon", "coverage", "calibrated"]
            ].assign(coverage=lambda d: d["coverage"].map(_pct))
        ),
        "",
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--burn-in-start", default="2016-01-01")
    p.add_argument("--window", type=int, default=156)
    p.add_argument("--min-calib", type=int, default=52)
    p.add_argument("--gamma", type=float, default=0.005)
    p.add_argument("--vol-window", type=int, default=12, help="weeks of returns for trailing volatility")
    p.add_argument("--out", type=Path, default=ROOT / "reports" / "calibration")
    args = p.parse_args(argv)
    t0 = time.perf_counter()

    y, X = load_dataset()
    fingerprint = data_fingerprint()  # at load time: files may change during a run
    eval_start = y.index[train_size(len(y)) - 1]  # same first scored origin as step 1a
    first = int(y.index.searchsorted(pd.Timestamp(args.burn_in_start)))
    cfg = BacktestConfig(first_origin=first, horizon=12, step=1, refit_every=52)
    forecasters = [Naive(), SarimaxForecaster("SARIMA (no exog)", SarimaxEstimator(use_exog=False), "none")]
    print(f"Backtest from {y.index[first].date()} ({len(cfg.origins(len(y)))} origins)...", flush=True)
    fc = run_backtest(y, X, forecasters, cfg, progress=_progress)

    print("Building conformal intervals...", flush=True)
    vol = conformal.trailing_volatility(y, window=args.vol_window)
    fc["vol_origin"] = fc["origin"].map(vol)
    kw = dict(window=args.window, min_calib=args.min_calib, gamma=args.gamma)
    parts = []
    for _, g in fc.groupby("model", sort=False):
        parts.append(conformal.conformal_intervals(g, **kw))
        parts.append(conformal.conformal_intervals(g, scale_col="vol_origin", include_native=False, **kw))
    iv = pd.concat(parts, ignore_index=True)
    iv = iv[iv["origin"] >= eval_start].copy()
    iv["regime"] = calibration.regime_label(iv["target_date"])

    summary = calibration.summarize_intervals(iv)
    by_regime = calibration.summarize_intervals(iv, group_extra=["regime"])
    selection = calibration.select_methods(summary)
    scorecard, verdict = calibration.regime_scorecard(by_regime)

    meta = {
        "vol_window": args.vol_window,
        "first_origin": str(y.index[first].date()),
        "last_origin": str(y.index[cfg.origins(len(y))[-1]].date()),
        "eval_start": str(eval_start.date()),
        "n_eval_origins": int(iv["origin"].nunique()),
        "window": args.window,
        "min_calib": args.min_calib,
        "gamma": args.gamma,
        "data_fingerprint": json.dumps(fingerprint),
        "git_commit": _git_commit(),
        "runtime_seconds": round(time.perf_counter() - t0, 1),
    }
    out: Path = args.out
    out.mkdir(parents=True, exist_ok=True)
    iv.to_csv(out / "intervals.csv", index=False)
    summary.to_csv(out / "calibration_summary.csv", index=False)
    by_regime.to_csv(out / "calibration_by_regime.csv", index=False)
    selection.to_csv(out / "selection.csv", index=False)
    scorecard.to_csv(out / "regime_scorecard.csv", index=False)
    (out / "run_meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    (out / "report.md").write_text(
        render(meta, summary, by_regime, selection, scorecard, verdict), encoding="utf-8"
    )
    print(f"Done in {meta['runtime_seconds']}s -> {out / 'report.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
